const { app, BrowserWindow, dialog, session, clipboard } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const os = require('node:os');
const { Diagnostics } = require('../src/diagnostics.cjs');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'output/playwright');
const profile = require('node:fs').mkdtempSync(path.join(os.tmpdir(), 'dualcast-logs-ui-'));
app.setPath('userData', profile);
let copied = '';
clipboard.writeText = text => { copied = text; };
let exportMode = 'save';
dialog.showSaveDialog = async (_, options) => exportMode === 'cancel' ? { canceled: true }
  : { canceled: false, filePath: exportMode === 'fail' ? path.join(out, 'missing-folder', 'fail.json') : path.join(out, `diagnostics-export.${options.filters[0].extensions[0]}`) };
require('../src/main.cjs');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, label) {
  for (let i = 0; i < 100; i++) { if (await fn()) return; await pause(100); }
  throw new Error(`Timed out: ${label}`);
}
app.whenReady().then(async () => {
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_, callback) => callback({ cancel: true }));
  await fs.mkdir(out, { recursive: true });
  await until(() => BrowserWindow.getAllWindows().length, 'main window');
  const main = BrowserWindow.getAllWindows()[0];
  const js = code => main.webContents.executeJavaScript(code, true);
  await until(async () => { try { return await js(`!!document.getElementById('tab-logs')?.onclick`); } catch { return false; } }, 'UI initialized');
  await js(`document.getElementById('tab-logs').click()`);
  await until(() => js(`!document.getElementById('logs-mode').hidden`), 'logs tab');
  assert.equal(await js(`document.getElementById('broadcast-workspace').hidden`), true);
  await js(`window.dualcast.select({id:'window:missing:0'}).catch(()=>{})`);
  await js(`window.dualcast.saveDestination({server:'bad-server',key:'TEST-PRIVATE-KEY'}).catch(()=>{})`);
  await js(`window.dualcast.diagnostic({module:'audio',level:'error',action:'fixture',message:'TEST-PRIVATE-KEY rtmp://host/live/private?txSecret=secret'});window.dualcast.diagnostic({module:'crop',level:'error',action:'fixture',message:'<img src=x onerror=alert(1)>'});setTimeout(()=>{Promise.reject(new Error('fixture async failure'))},0)`);
  await until(() => js(`document.getElementById('log-entries').textContent.includes('fixture async failure')`), 'global error captured');
  assert.equal(await js(`document.querySelector('#log-entries img') === null`), true);
  const snapshot = await js(`window.dualcast.logsSnapshot()`);
  const text = JSON.stringify(snapshot);
  for (const secret of ['TEST-PRIVATE-KEY', 'rtmp://host', 'txSecret=secret']) assert(!text.includes(secret));
  for (const module of ['app', 'capture', 'audio', 'crop', 'settings']) assert(snapshot.entries.some(entry => entry.module === module));
  await js(`document.getElementById('log-module').value='audio';document.getElementById('log-module').dispatchEvent(new Event('change'))`);
  assert.equal(await js(`Array.from(document.querySelectorAll('#log-entries tr')).every(row=>row.children[2].textContent==='音频')`), true);
  await js(`document.getElementById('log-search').value='does-not-exist';document.getElementById('log-search').dispatchEvent(new Event('input'))`);
  assert.equal(await js(`!document.getElementById('log-empty').hidden`), true);
  await js(`document.getElementById('log-search').value='';document.getElementById('log-module').value='';document.getElementById('log-module').dispatchEvent(new Event('change'));document.getElementById('log-copy').click()`);
  await until(() => copied.length > 0, 'copy report');
  assert(JSON.parse(copied).metadata.electron);
  await js(`document.getElementById('log-export').click()`);
  await until(async () => { try { return (await fs.stat(path.join(out, 'diagnostics-export.json'))).size > 0; } catch { return false; } }, 'export');
  const exported = JSON.parse(await fs.readFile(path.join(out, 'diagnostics-export.json'), 'utf8'));
  assert(exported.entries.some(entry => entry.module === 'audio'));
  assert(!JSON.stringify(exported).includes('TEST-PRIVATE-KEY'));
  await until(() => js(`!document.getElementById('log-export').disabled`), 'export complete');
  await js(`document.getElementById('log-export-text').click()`);
  await until(() => js(`document.getElementById('log-feedback').textContent==='错误日志.txt 已导出。'`), 'TXT export complete');
  const exportedText = await fs.readFile(path.join(out, 'diagnostics-export.txt'), 'utf8');
  assert(exportedText.startsWith('\uFEFF双播台错误日志\r\n'));
  assert(exportedText.includes('[音频]'));
  assert(exportedText.includes('fixture async failure'));
  assert(!exportedText.includes('TEST-PRIVATE-KEY'));
  exportMode = 'cancel';
  await js(`document.getElementById('log-export-text').click()`);
  await until(() => js(`document.getElementById('log-feedback').textContent==='已取消导出。'`), 'export cancel');
  exportMode = 'fail';
  await js(`document.getElementById('log-export-text').click()`);
  await until(() => js(`document.getElementById('log-entries').textContent.includes('导出诊断报告失败')`), 'export failure captured');
  await fs.writeFile(path.join(out, 'logs-desktop.png'), await main.webContents.capturePage().then(image => image.toPNG()));
  main.setSize(480, 800);
  await pause(300);
  assert.equal(await js(`document.documentElement.scrollWidth <= innerWidth`), true);
  await fs.writeFile(path.join(out, 'logs-compact.png'), await main.webContents.capturePage().then(image => image.toPNG()));
  const recovered = new Diagnostics(path.join(profile, 'diagnostics'));
  assert(recovered.snapshot().entries.some(entry => entry.action === 'fixture'));
  await js(`for(let i=0;i<65;i++)window.dualcast.diagnostic({module:'crop',level:'info',action:'page-test-'+i,message:'分页测试 '+i})`);
  await until(() => js(`document.querySelectorAll('#log-entries tr').length===50`), 'page cap');
  await js(`document.getElementById('log-next').click()`);
  assert.equal(await js(`document.getElementById('log-page').textContent.includes('第 2')`), true);
  await js(`document.getElementById('log-level').value='error';document.getElementById('log-level').dispatchEvent(new Event('change'))`);
  assert.equal(await js(`Array.from(document.querySelectorAll('#log-entries tr')).every(row=>row.dataset.level==='error')`), true);
  main.setSize(700, 800);
  await pause(200);
  assert.equal(await js(`document.documentElement.scrollWidth <= innerWidth`), true);
  await js(`document.getElementById('log-clear').click()`);
  await until(() => js(`document.getElementById('confirmation').open`), 'clear confirmation');
  await js(`document.getElementById('cancel-confirm').click()`);
  assert((await js(`window.dualcast.logsSnapshot()`)).entries.length > 0);
  await js(`document.getElementById('log-clear').click();document.getElementById('accept-confirm').click()`);
  await until(async () => (await js(`window.dualcast.logsSnapshot()`)).entries.length === 0, 'clear');
  assert.equal(new Diagnostics(path.join(profile, 'diagnostics')).snapshot().entries.length, 0);
  console.log('PASS logs tab, capture/config/global errors, redaction, safe text, filtering/search, copy, export/cancel/failure, clear/cancel, restart persistence and 480px layout');
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
